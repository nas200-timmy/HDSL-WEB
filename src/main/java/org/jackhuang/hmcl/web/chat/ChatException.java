package org.jackhuang.hmcl.web.chat;

import org.jetbrains.annotations.NotNullByDefault;

/// 聊天 API 的可读失败：HTTP 层把 `status` 和 `code` 原样交给前端。
@NotNullByDefault
public final class ChatException extends Exception {

    private final int status;
    private final String code;

    public ChatException(int status, String code, String message) {
        super(message);
        this.status = status;
        this.code = code;
    }

    public int status() {
        return status;
    }

    public String code() {
        return code;
    }
}