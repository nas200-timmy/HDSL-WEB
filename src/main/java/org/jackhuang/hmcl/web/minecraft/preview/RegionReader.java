import java.util.zip.GZIPInputStream;
import java.util.zip.InflaterInputStream;

/// Reads `.mca` region files into the few facts a seed map needs.
///
/// The world is generated by the **real server**, so this class only has to
/// understand the file format the game wrote — never the generator itself.
/// That is the whole point of the design: the panel cannot drift from the game
/// because it never re-implements the game.
///
/// Three chunk layouts exist and all three are handled:
///
/// - 1.12 and older: `Level.Biomes` is a `byte[256]`, one entry per block;
/// - 1.13 – 1.17: `Level.Biomes` is an `int[1024]`, a 4×4×64 grid;
/// - 1.18 and newer: `sections[].biomes` is a paletted 4×4×4 container.
///
/// The array length decides the era — not the version string — because a
/// datapack or a pre-release can move the boundary.
@NotNullByDefault
public final class RegionReader {

    /// One generated structure start, as the world stores it.
    ///
    /// @param id      the structure id, normalised (`village`, `monument`)
    /// @param chunkX  the chunk the start sits in
    /// @param chunkZ  the chunk the start sits in
    public record StructureRef(String id, int chunkX, int chunkZ) {
    }

    /// The slice of one chunk the map needs.
    ///
    /// @param chunkX     chunk coordinate
    /// @param chunkZ     chunk coordinate
    /// @param biomes     sixteen names, indexed `z4 * 4 + x4` within the chunk
    /// @param heights    sixteen surface heights, same indexing; empty when the
    ///                   chunk carries no heightmap (very old worlds)
    /// @param blocks     sixteen surface block names (`grass_block`), same
    ///                   indexing; empty for versions whose block storage is
    ///                   not paletted (1.12 and older)
    /// @param structures structure starts, possibly empty
    public record ChunkSummary(int chunkX, int chunkZ, String[] biomes, int[] heights,
                               String[] blocks, List<StructureRef> structures) {
    }

    private static final int SECTOR = 4096;

    private RegionReader() {
    }

    /// Counts the chunks a region directory already holds.
    ///
    /// The generation wait uses this as its only honest progress signal: the
    /// `forceload` command returns long before the chunks reach disk.
    ///
    /// @param regionDirectory `<world>/region`
    /// @return the number of present chunks across every region file
    public static int countPresentChunks(Path regionDirectory) {
        return countPresentChunks(regionDirectory, Integer.MIN_VALUE, Integer.MAX_VALUE);
    }

    /// Counts the chunks inside a chunk-coordinate square.
    ///
    /// The square matters: a fresh world already has spawn chunks around 0,0
    /// before the preview asks for anything, and counting those would report a
    /// finished map a second after the server started.
    ///
    /// @param regionDirectory `<world>/region`
    /// @param fromChunk       the lowest chunk coordinate included (both axes)
    /// @param toChunk         the highest chunk coordinate included
    /// @return the number of present chunks inside the square
    public static int countPresentChunks(Path regionDirectory, int fromChunk, int toChunk) {
        if (!Files.isDirectory(regionDirectory)) {
            return 0;
        }
        int total = 0;
        try (var files = Files.list(regionDirectory)) {
            for (Path file : files.toList()) {
                String name = file.getFileName().toString();
                if (!name.startsWith("r.") || !name.endsWith(".mca")) {
                    continue;
                }
                total += countInFile(file, fromChunk, toChunk);
            }
        } catch (IOException ignored) {
            // A region file being written can vanish between list and read;
            // the next poll gets it.
        }
        return total;
    }

    private static int countInFile(Path file, int fromChunk, int toChunk) {
        String[] parts = file.getFileName().toString().substring(2, file.getFileName().toString().length() - 4)
                .split("\\.");
        if (parts.length != 2) {
            return 0;
        }
        int regionX;
        int regionZ;
        try {
            regionX = Integer.parseInt(parts[0]);
            regionZ = Integer.parseInt(parts[1]);
        } catch (NumberFormatException e) {
            return 0;
        }
        try {
            byte[] header = new byte[SECTOR];
            try (InputStream in = Files.newInputStream(file)) {
                if (in.readNBytes(header, 0, SECTOR) < SECTOR) {
                    return 0;
                }
            }
            int count = 0;
            for (int i = 0; i < 1024; i++) {
                int base = i * 4;
                if (header[base] == 0 && header[base + 1] == 0 && header[base + 2] == 0) {
                    continue;
                }
                int chunkX = (regionX << 5) | (i & 31);
                int chunkZ = (regionZ << 5) | (i >> 5);
                if (chunkX >= fromChunk && chunkX <= toChunk && chunkZ >= fromChunk && chunkZ <= toChunk) {
                    count++;
                }
            }
            return count;
        } catch (IOException ignored) {
            return 0;
        }
    }

    /// Reads every chunk of one region file.
    ///
    /// @param file    the `.mca`
    /// @param regionX the region's x, from the file name
    /// @param regionZ the region's z, from the file name
    /// @param biomeY  the height the flat biome layer is sampled at
    /// @return the chunks that parsed
    /// @throws IOException when the file itself cannot be read
    public static List<ChunkSummary> read(Path file, int regionX, int regionZ, int biomeY) throws IOException {
        byte[] all = Files.readAllBytes(file);
        List<ChunkSummary> chunks = new ArrayList<>();
        for (int index = 0; index < 1024; index++) {
            int base = index * 4;
            if (base + 4 > all.length) {
                break;
            }
            int offset = ((all[base] & 0xFF) << 16) | ((all[base + 1] & 0xFF) << 8) | (all[base + 2] & 0xFF);
            if (offset == 0) {
                continue;
            }
            long position = (long) offset * SECTOR;
            if (position + 5 > all.length) {
                continue;
            }
            int length = readInt(all, (int) position);
            if (length < 1 || position + 4 + length > all.length) {
                continue;
            }
            int compression = all[(int) position + 4] & 0xFF;
            byte[] payload = Arrays.copyOfRange(all, (int) position + 5, (int) position + 4 + length);
            byte[] raw;
            try {
                raw = decompress(payload, compression);
            } catch (IOException e) {
                continue;
            }
            Map<String, Object> root;
            try {
                root = Nbt.read(raw);
            } catch (IOException e) {
                continue;
            }
            int chunkX = (regionX << 5) | (index & 31);
            int chunkZ = (regionZ << 5) | (index >> 5);
            ChunkSummary summary = summarise(root, chunkX, chunkZ, biomeY);
            if (summary != null) {
                chunks.add(summary);
            }
        }
        return chunks;
    }

    private static @Nullable ChunkSummary summarise(Map<String, Object> root, int chunkX, int chunkZ, int biomeY) {
        // 1.18 flattened the chunk: no `Level` wrapper. Older versions have it.
        Map<String, Object> level = Nbt.compound(root.get("Level"));
        Map<String, Object> body = level != null ? level : root;
        String[] biomes = biomes(root, body, biomeY, heights(body));
        if (biomes == null) {
            return null;
        }
        int[] surface = heights(body);
        return new ChunkSummary(chunkX, chunkZ, biomes, surface, surfaceBlocks(root, surface),
                structures(root, body, chunkX, chunkZ));
    }

    // ------------------------------------------------------------------ biomes --

    private static @Nullable String[] biomes(Map<String, Object> root, Map<String, Object> body,
                                             int biomeY, int[] heights) {
        Object legacy = body.get("Biomes");
        if (legacy instanceof byte[] bytes && bytes.length >= 256) {
            // One byte per block: the pre-1.13 two-dimensional array.
            return fromDense(bytes, true, biomeY, heights);
        }
        if (legacy instanceof int[] ints && ints.length >= 256) {
            // 1.15 – 1.17 stores a 4×4×64 grid; 1.13 – 1.14 still one per block.
            return fromDense(ints, ints.length < 1024, biomeY, heights);
        }
        return fromSections(root, body, biomeY, heights);
    }

    /// The 2D and 3D legacy arrays. `perBlock` means 16×16 entries covering one
    /// block each; otherwise the array is a 4×4×64 grid of 4×4×4 cells.
    private static String[] fromDense(@Nullable Object array, boolean perBlock, int biomeY, int[] heights) {
        String[] biomes = new String[16];
        if (array == null) {
            return biomes;
        }
        if (perBlock) {
            for (int z4 = 0; z4 < 4; z4++) {
                for (int x4 = 0; x4 < 4; x4++) {
                    int x = x4 * 4;
                    int z = z4 * 4;
                    int index = z * 16 + x;
                    biomes[z4 * 4 + x4] = legacyName(valueAt(array, index));
                }
            }
            return biomes;
        }
        for (int z4 = 0; z4 < 4; z4++) {
            for (int x4 = 0; x4 < 4; x4++) {
                // The slice that matters is the one at the surface, not a fixed
                // height: a cave under a forest is not the forest's biome.
                int height = cellHeight(heights, z4, x4, biomeY);
                int y4 = Math.max(0, Math.min(63, height >> 2));
                int index = y4 * 16 + z4 * 4 + x4;
                biomes[z4 * 4 + x4] = legacyName(valueAt(array, index));
            }
        }
        return biomes;
    }

    private static String legacyName(int id) {
        String name = BiomePalette.legacyName(id);
        return name != null ? name : "unknown_" + id;
    }

    private static String[] fromSections(Map<String, Object> root, Map<String, Object> body,
                                         int biomeY, int[] heights) {
        Map<Integer, Map<String, Object>> sections = new HashMap<>();
        for (Object element : Nbt.list(root.get("sections"))) {
            Map<String, Object> section = Nbt.compound(element);
            if (section != null) {
                sections.put(Nbt.integer(section.get("Y"), Integer.MIN_VALUE), section);
            }
        }
        String[] biomes = new String[16];
        boolean any = false;
        for (int z4 = 0; z4 < 4; z4++) {
            for (int x4 = 0; x4 < 4; x4++) {
                // Sample at the surface of this 4×4 column. Sampling at a fixed
                // height paints underground cave biomes over the forest above
                // them, which is both wrong on the map and wrong in the report.
                int height = cellHeight(heights, z4, x4, biomeY);
                int sectionIndex = height >> 4;
                int yInSection = (height & 15) >> 2;
                Map<String, Object> section = sections.get(sectionIndex);
                if (section == null) {
                    biomes[z4 * 4 + x4] = "unknown";
                    continue;
                }
                Map<String, Object> container = Nbt.compound(section.get("biomes"));
                if (container == null) {
                    biomes[z4 * 4 + x4] = "unknown";
                    continue;
                }
                List<?> palette = Nbt.list(container.get("palette"));
                long[] data = container.get("data") instanceof long[] values ? values : new long[0];
                int paletteSize = Math.max(1, palette.size());
                // Biome containers use a one-bit minimum (block containers use
                // four); a single-palette section carries no data array at all.
                int bits = Math.max(1, 32 - Integer.numberOfLeadingZeros(paletteSize - 1));
                int perLong = 64 / bits;
                int index = yInSection * 16 + z4 * 4 + x4;
                int value = 0;
                int word = index / perLong;
                if (data.length > word) {
                    long packed = data[word];
                    int shift = (index % perLong) * bits;
                    value = (int) ((packed >>> shift) & ((1L << bits) - 1));
                }
                biomes[z4 * 4 + x4] = paletteName(palette, value);
                any = true;
            }
        }
        // A chunk without any section at the sampled heights (superflat, or a y
        // outside the column) still renders, just as unknown.
        return any ? biomes : null;
    }

    /// The highest surface in one 4×4 cell, or the fallback when the chunk has
    /// no heightmap.
    private static int cellHeight(int[] heights, int z4, int x4, int fallback) {
        if (heights.length < 256) {
            return fallback;
        }
        int best = 0;
        for (int dz = 0; dz < 4; dz++) {
            for (int dx = 0; dx < 4; dx++) {
                best = Math.max(best, heights[(z4 * 4 + dz) * 16 + x4 * 4 + dx]);
            }
        }
        return best;
    }

    private static String paletteName(List<?> palette, int index) {
        if (index < 0 || index >= palette.size()) {
            return "unknown";
        }
        Object entry = palette.get(index);
        if (entry instanceof String name) {
            return normaliseBiome(name);
        }
        if (entry instanceof Number number) {
            return legacyName(number.intValue());
        }
        if (entry instanceof Map<?, ?> map && map.get("Name") instanceof String name) {
            // 1.13 – 1.17 paletted containers wrap the name in a compound.
            return normaliseBiome(name);
        }
        return "unknown";
    }

    /// Biome names enter the map without their namespace, so every era and the
    /// colour table agree on one spelling (`plains`, not `minecraft:plains`).
    static String normaliseBiome(@Nullable String raw) {
        if (raw == null || raw.isBlank()) {
            return "unknown";
        }
        String value = raw.trim();
        int colon = value.indexOf(':');
        if (colon >= 0) {
            value = value.substring(colon + 1);
        }
        return value.toLowerCase(Locale.ROOT);
    }

    private static int valueAt(Object array, int index) {
        if (array instanceof byte[] bytes) {
            return index < bytes.length ? bytes[index] & 0xFF : 0;
        }
        if (array instanceof int[] ints) {
            return index < ints.length ? ints[index] : 0;
        }
        return 0;
    }

    // ------------------------------------------------------------------ height --

    /// The terrain surface of a 16×16 chunk, indexed `z * 16 + x`.
    ///
    /// Two layouts exist: 1.14 and later store named heightmaps as 9-bit packed
    /// longs (`Heightmaps.MOTION_BLOCKING`), while 1.12 and older store a plain
    /// `HeightMap` byte array. The packed values never straddle a long, which is
    /// the same rule the biome palette follows.
    private static int[] heights(Map<String, Object> body) {
        Map<String, Object> maps = Nbt.compound(body.get("Heightmaps"));
        if (maps != null) {
            for (String name : List.of("MOTION_BLOCKING", "WORLD_SURFACE", "OCEAN_FLOOR")) {
                if (maps.get(name) instanceof long[] packed) {
                    return unpack9(packed);
                }
            }
        }
        Object legacy = body.get("HeightMap");
        if (legacy instanceof byte[] bytes && bytes.length >= 256) {
            int[] values = new int[256];
            for (int i = 0; i < 256; i++) {
                values[i] = bytes[i] & 0xFF;
            }
            return values;
        }
        if (legacy instanceof int[] ints && ints.length >= 256) {
            return Arrays.copyOf(ints, 256);
        }
        return new int[0];
    }

    private static int[] unpack9(long[] packed) {
        int[] values = new int[256];
        int perLong = 64 / 9;
        for (int i = 0; i < 256; i++) {
            int word = i / perLong;
            if (word >= packed.length) {
                break;
            }
            values[i] = (int) ((packed[word] >>> ((i % perLong) * 9)) & 0x1FF);
        }
        return values;
    }

    // ------------------------------------------------------------------ blocks --

    /// The top block of every column, from the 1.18+ paletted block storage.
    ///
    /// A seed map is read from the surface material, not the height: a forest
    /// is one colour because the top block is leaves or grass everywhere, while
    /// the height under it bumps by a block from tree to tree. Without this the
    /// hillshade turns every canopy into noise.
    ///
    /// @return 256 names, or an empty array when the chunk is not paletted
    private static String[] surfaceBlocks(Map<String, Object> root, int[] heights) {
        List<?> sections = Nbt.list(root.get("sections"));
        if (sections.isEmpty() || heights.length < 256) {
            return new String[0];
        }
        Map<Integer, Map<String, Object>> bySection = new HashMap<>();
        for (Object element : sections) {
            Map<String, Object> section = Nbt.compound(element);
            if (section != null) {
                bySection.put(Nbt.integer(section.get("Y"), Integer.MIN_VALUE), section);
            }
        }
        String[] blocks = new String[256];
        for (int z = 0; z < 16; z++) {
            for (int x = 0; x < 16; x++) {
                int height = heights[z * 16 + x];
                if (height < 0) {
                    continue;
                }
                Map<String, Object> section = bySection.get(height >> 4);
                if (section == null) {
                    continue;
                }
                Map<String, Object> states = Nbt.compound(section.get("block_states"));
                if (states == null) {
                    continue;
                }
                List<?> palette = Nbt.list(states.get("palette"));
                long[] data = states.get("data") instanceof long[] values ? values : new long[0];
                int index = ((height & 15) * 16 + z) * 16 + x;
                int paletteSize = Math.max(1, palette.size());
                // Block containers start at four bits, unlike the one-bit biome
                // containers.
                int bits = Math.max(4, 32 - Integer.numberOfLeadingZeros(paletteSize - 1));
                int perLong = 64 / bits;
                int value = 0;
                if (data.length > index / perLong) {
                    value = (int) ((data[index / perLong] >>> ((index % perLong) * bits))
                            & ((1L << bits) - 1));
                }
                blocks[z * 16 + x] = blockName(palette, value);
            }
        }
        return blocks;
    }

    private static String blockName(List<?> palette, int index) {
        if (index < 0 || index >= palette.size()) {
            return "unknown";
        }
        if (palette.get(index) instanceof Map<?, ?> entry && entry.get("Name") instanceof String name) {
            return normaliseBiome(name);
        }
        return "unknown";
    }

    // -------------------------------------------------------------- structures --

    private static List<StructureRef> structures(Map<String, Object> root, Map<String, Object> body,
                                                 int chunkX, int chunkZ) {
        Map<String, Object> structures = Nbt.compound(body.get("Structures"));
        if (structures == null) {
            structures = Nbt.compound(root.get("structures"));
        }
        if (structures == null) {
            return List.of();
        }
        // Two layouts have to be read together. 1.18+ writes real starts into
        // `starts`; 1.13 – 1.17 mostly writes `{id: INVALID}` placeholders there
        // and keeps the positions in `References`, where each structure maps to
        // a LongArray of start chunk positions.
        java.util.LinkedHashMap<String, StructureRef> found = new java.util.LinkedHashMap<>();
        Map<String, Object> starts = Nbt.compound(structures.get("Starts"));
        if (starts == null) {
            starts = Nbt.compound(structures.get("starts"));
        }
        if (starts != null) {
            for (Map.Entry<String, Object> entry : starts.entrySet()) {
                Map<String, Object> start = Nbt.compound(entry.getValue());
                if (start == null || !start.containsKey("ChunkX")) {
                    // `{id: INVALID}` is a placeholder: the start lives in
                    // another chunk and is reported through References.
                    continue;
                }
                String id = start.get("id") instanceof String explicit ? explicit : entry.getKey();
                if ("invalid".equalsIgnoreCase(id)) {
                    // `StructureStart.INVALID` carries a 0,0 position: it means
                    // "checked, nothing here", not a structure at spawn.
                    continue;
                }
                int x = Nbt.integer(start.get("ChunkX"), 0);
                int z = Nbt.integer(start.get("ChunkZ"), 0);
                found.putIfAbsent(x + "," + z + "," + id, new StructureRef(normaliseStructure(id), x, z));
            }
        }
        Map<String, Object> references = Nbt.compound(structures.get("References"));
        if (references != null) {
            for (Map.Entry<String, Object> entry : references.entrySet()) {
                if (!(entry.getValue() instanceof long[] positions)) {
                    continue;
                }
                for (long packed : positions) {
                    int x = (int) packed;
                    int z = (int) (packed >> 32);
                    // A reference list is repeated in every chunk the structure
                    // touches; only the owning chunk reports it, so one start
                    // yields one marker.
                    if (x != chunkX || z != chunkZ) {
                        continue;
                    }
                    found.putIfAbsent(x + "," + z + "," + entry.getKey(),
                            new StructureRef(normaliseStructure(entry.getKey()), x, z));
                }
            }
        }
        return List.copyOf(found.values());
    }

    /// Legacy keys are capitalised (`Village`); modern ones are resource
    /// locations (`minecraft:village_plains`). Both collapse to a short id the
    /// UI can label.
    static String normaliseStructure(@Nullable String raw) {
        if (raw == null || raw.isBlank()) {
            return "structure";
        }
        String value = raw.trim();
        int colon = value.indexOf(':');
        if (colon >= 0) {
            value = value.substring(colon + 1);
        }
        return value.toLowerCase(Locale.ROOT);
    }

    // ------------------------------------------------------------------ utility --

    private static byte[] decompress(byte[] payload, int compression) throws IOException {
        if (compression == 3) {
            return payload;
        }
        InputStream in = compression == 1
                ? new GZIPInputStream(new java.io.ByteArrayInputStream(payload))
                : compression == 2
                        ? new InflaterInputStream(new java.io.ByteArrayInputStream(payload))
                        : null;
        if (in == null) {
            throw new IOException("unknown chunk compression " + compression);
        }
        try (in) {
            ByteArrayOutputStream out = new ByteArrayOutputStream(Math.max(1024, payload.length * 4));
            in.transferTo(out);
            return out.toByteArray();
        }
    }

    private static int readInt(byte[] data, int offset) {
        return ((data[offset] & 0xFF) << 24)
                | ((data[offset + 1] & 0xFF) << 16)
                | ((data[offset + 2] & 0xFF) << 8)
                | (data[offset + 3] & 0xFF);
    }
}
